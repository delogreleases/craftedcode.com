/* CraftedSoft: site behaviour (no dependencies).
   All markup is static HTML (generated by tools/build.mjs); this file only adds
   interaction: theme, menus, reveal-on-scroll, 3D effects, tabs and the form. */
;(function () {
  const SITE = window.CS_SITE || { contact: {}, products: [] }
  const C = SITE.contact || {}
  const doc = document.documentElement
  const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches
  const finePointer = matchMedia('(pointer: fine)').matches
  const $ = (s, r = document) => r.querySelector(s)
  const $$ = (s, r = document) => [...r.querySelectorAll(s)]
  const clamp = (v, a, b) => Math.min(b, Math.max(a, v))

  /* ---------- Opened straight from disk (file://) ----------
     Clean folder links (about/, products/chittill/) need a web server to open their index.html; from disk the
     browser shows a file listing instead. So on file:// only, point those links at the folder's index.html.
     Hosted online (http/https) nothing changes and the addresses stay clean. */
  const LOCAL = location.protocol === 'file:'
  const toFile = (href) => {
    if (!LOCAL || /^([a-z]+:|#|\/\/)/i.test(href)) return href
    const m = href.match(/^([^?#]*)(.*)$/)
    const path = m[1]
    return path === '' || path.endsWith('/') ? `${path || './'}index.html${m[2]}` : href
  }
  if (LOCAL) $$('a[href]').forEach((a) => { const h = a.getAttribute('href'); const f = toFile(h); if (f !== h) a.setAttribute('href', f) })
  // Page-to-page transitions are skipped where the browser doesn't allow them (e.g. file://); it reports that as a
  // rejected promise, so mark those as handled to keep the console clean.
  const quiet = (vt) => { if (vt) ['ready', 'finished', 'updateCallbackDone'].forEach((k) => vt[k]?.catch?.(() => {})) }
  addEventListener('pagereveal', (e) => quiet(e.viewTransition))
  addEventListener('pageswap', (e) => quiet(e.viewTransition))

  /* ---------- Clean addresses: a #fragment never stays in the address bar ----------
     Old links such as index.html#about forward to the page that now holds that section;
     any other fragment is removed once the browser has scrolled to it. */
  const LEGACY = { about: 'about/', commitments: 'about/', services: 'services/', process: 'services/' }
  if (location.hash) {
    const id = decodeURIComponent(location.hash.slice(1))
    if (!document.getElementById(id) && LEGACY[id]) {
      location.replace(toFile((doc.dataset.root || '') + LEGACY[id]))
      return
    }
    const target = document.getElementById(id)
    history.replaceState(history.state, '', location.pathname + location.search)
    if (target) requestAnimationFrame(() => target.scrollIntoView({ block: 'start', behavior: 'instant' }))
  }
  addEventListener('hashchange', () => history.replaceState(history.state, '', location.pathname + location.search))
  // Same-page links (#features, skip link…) scroll smoothly without writing the fragment into the URL.
  document.addEventListener('click', (e) => {
    const a = e.target.closest && e.target.closest('a[href^="#"]')
    if (!a || e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return
    const id = a.getAttribute('href').slice(1)
    const target = id && document.getElementById(id)
    if (!target) return
    e.preventDefault()
    target.scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth', block: 'start' })
    if (a.classList.contains('skip')) {
      target.setAttribute('tabindex', '-1')
      target.focus({ preventScroll: true })
    }
  })

  /* ---------- Reveal on scroll ----------
     Anything already on screen at load is shown at once (no fade), so a page
     never "re-animates" when you navigate to it. Only content further down fades in. */
  const reveals = $$('.reveal')
  const vh = innerHeight
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e) => { if (e.isIntersecting) { e.target.classList.add('is-in'); io.unobserve(e.target) } })
  }, { rootMargin: '0px 0px -6% 0px', threshold: 0.06 })
  reveals.forEach((el) => {
    if (el.getBoundingClientRect().top < vh) {
      el.classList.add('no-anim', 'is-in')
      return
    }
    const sibs = $$(':scope > .reveal', el.parentElement)
    const i = sibs.indexOf(el)
    if (i > 0) el.style.setProperty('--d', `${Math.min(i, 5) * 0.06}s`)
    io.observe(el)
  })
  requestAnimationFrame(() => requestAnimationFrame(() => $$('.no-anim').forEach((el) => el.classList.remove('no-anim'))))

  /* ---------- Theme ---------- */
  const setTheme = (t, save) => {
    doc.dataset.theme = t
    const meta = $('meta[name="theme-color"]')
    if (meta) meta.content = t === 'dark' ? '#0a0b0f' : '#ffffff'
    if (save) try { localStorage.setItem('cs-theme', t) } catch (e) { /* storage blocked */ }
    $$('.theme-btn').forEach((b) => {
      const label = t === 'dark' ? 'Switch to day mode' : 'Switch to night mode'
      b.setAttribute('aria-label', label)
      b.title = label
    })
  }
  setTheme(doc.dataset.theme || 'light', false)
  $$('.theme-btn').forEach((b) =>
    b.addEventListener('click', () => {
      const next = doc.dataset.theme === 'dark' ? 'light' : 'dark'
      // Cross-fade the whole page between themes where supported.
      if (document.startViewTransition && !reduceMotion) document.startViewTransition(() => setTheme(next, true))
      else setTheme(next, true)
    })
  )
  matchMedia('(prefers-color-scheme: dark)').addEventListener('change', (e) => {
    let saved = null
    try { saved = localStorage.getItem('cs-theme') } catch (err) { /* ignore */ }
    if (!saved) setTheme(e.matches ? 'dark' : 'light', false)
  })

  /* ---------- Header ---------- */
  const hdr = $('#hdr')
  if (hdr) {
    const onScroll = () => hdr.classList.toggle('is-scrolled', scrollY > 8)
    onScroll()
    addEventListener('scroll', onScroll, { passive: true })

    const dd = $('#dd-products')
    if (dd) {
      const btn = $('button', dd)
      let timer
      const open = (v) => { dd.classList.toggle('is-open', v); hdr.classList.toggle('dd-open', v); btn.setAttribute('aria-expanded', String(v)) }
      btn.addEventListener('click', () => open(!dd.classList.contains('is-open')))
      if (finePointer) {
        dd.addEventListener('mouseenter', () => { clearTimeout(timer); open(true) })
        dd.addEventListener('mouseleave', () => { timer = setTimeout(() => open(false), 160) })
      }
      document.addEventListener('click', (e) => { if (!dd.contains(e.target)) open(false) })
      document.addEventListener('keydown', (e) => { if (e.key === 'Escape') open(false) })
    }

    // Sliding highlight that follows the pointer across the main links.
    const nav = $('.hdr__nav', hdr)
    const ink = $('.hdr__ink', hdr)
    if (nav && ink && finePointer) {
      const targets = $$(':scope > a, :scope > .dd > button', nav)
      const moveTo = (el) => {
        const nr = nav.getBoundingClientRect()
        const r = el.getBoundingClientRect()
        ink.style.width = `${r.width}px`
        ink.style.transform = `translateX(${r.left - nr.left}px)`
        ink.style.opacity = '1'
      }
      targets.forEach((el) => el.addEventListener('mouseenter', () => moveTo(el)))
      nav.addEventListener('mouseleave', () => { ink.style.opacity = '0' })
    }

    // Mobile: full-screen menu sheet.
    const burger = $('.burger', hdr)
    const mnav = $('#mnav')
    if (burger && mnav) {
      const setMenu = (v) => {
        burger.setAttribute('aria-expanded', String(v))
        burger.setAttribute('aria-label', v ? 'Close menu' : 'Open menu')
        hdr.classList.toggle('is-open', v)
        doc.style.overflow = v ? 'hidden' : ''
      }
      burger.addEventListener('click', () => setMenu(!hdr.classList.contains('is-open')))
      $$('a', mnav).forEach((a) => a.addEventListener('click', () => setMenu(false)))
      document.addEventListener('keydown', (e) => { if (e.key === 'Escape') setMenu(false) })
      addEventListener('resize', () => { if (innerWidth > 860) setMenu(false) })
    }
  }

  /* ---------- Product pages: hand the top of the screen to the product bar ---------- */
  const subnav = $('.subnav')
  if (hdr && subnav) {
    const sentinel = document.createElement('div')
    sentinel.setAttribute('aria-hidden', 'true')
    subnav.before(sentinel)
    // One bar at a time: the moment the product bar reaches the header, the header steps away, in
    // either scroll direction, and only returns once you are back above the product bar's place.
    let raf = 0
    const update = () => {
      raf = 0
      document.body.classList.toggle('nav-up', sentinel.getBoundingClientRect().top <= hdr.offsetHeight)
    }
    addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(update) }, { passive: true })
    addEventListener('resize', update)
    update()
  }

  /* ---------- Products catalogue: search + industry chips ---------- */
  const grid = $('#shop-grid')
  if (grid) {
    const q = $('#shop-q')
    const chips = $$('.cchip')
    const cards = $$('.pc[data-search]', grid).filter((c) => c.dataset.search !== '*')
    const build = $('.pc--build', grid)
    const count = $('#shop-count')
    const empty = $('#shop-empty')
    let industry = '*'
    const apply = () => {
      const terms = q.value.trim().toLowerCase().split(/\s+/).filter(Boolean)
      let shown = 0
      cards.forEach((c) => {
        const ok = (industry === '*' || c.dataset.industry === industry) && terms.every((t) => c.dataset.search.includes(t))
        c.hidden = !ok
        if (ok) shown++
      })
      if (build) build.hidden = shown === 0
      empty.hidden = shown > 0
      $('#shop-empty-q').textContent = q.value.trim() || (chips.find((c) => c.dataset.industry === industry)?.firstChild.textContent ?? '')
      count.textContent = `${shown} of ${cards.length} product${cards.length === 1 ? '' : 's'}`
      // Keep the filters in the address only as ?q= / ?industry= (shareable), never as a #fragment.
      const params = new URLSearchParams(location.search)
      q.value.trim() ? params.set('q', q.value.trim()) : params.delete('q')
      industry !== '*' ? params.set('industry', industry) : params.delete('industry')
      const qs = params.toString()
      history.replaceState(history.state, '', location.pathname + (qs ? `?${qs}` : ''))
      syncAudience()
    }
    // Hero switcher ("All products / I run a shop / I run a restaurant"): same filter as the chips, with a sliding pill.
    const auds = $$('.aud')
    const audPill = $('.aud__pill')
    function syncAudience() {
      let on = null
      auds.forEach((a) => { const pressed = a.dataset.industry === industry; a.setAttribute('aria-pressed', String(pressed)); if (pressed) on = a })
      if (audPill) {
        audPill.style.opacity = on ? '1' : '0'
        if (on) { audPill.style.width = `${on.offsetWidth}px`; audPill.style.transform = `translateX(${on.offsetLeft - 6}px)` }
      }
    }
    const setIndustry = (value) => {
      industry = value
      chips.forEach((x) => x.setAttribute('aria-pressed', String(x.dataset.industry === value)))
      apply()
    }
    chips.forEach((c) => c.addEventListener('click', () => setIndustry(c.dataset.industry)))
    auds.forEach((a) => a.addEventListener('click', () => setIndustry(a.dataset.industry)))
    addEventListener('resize', syncAudience)
    q.addEventListener('input', apply)
    $('#shop-clear')?.addEventListener('click', () => {
      q.value = ''; industry = '*'
      chips.forEach((x) => x.setAttribute('aria-pressed', String(x.dataset.industry === '*')))
      apply(); q.focus()
    })
    // "/" jumps to the search box, like most product catalogues.
    document.addEventListener('keydown', (e) => {
      if (e.key === '/' && !/input|textarea|select/i.test(document.activeElement?.tagName || '')) { e.preventDefault(); q.focus() }
      if (e.key === 'Escape' && document.activeElement === q && q.value) { q.value = ''; apply() }
    })
    // Start from a shared link (?q=gst&industry=Retail).
    const start = new URLSearchParams(location.search)
    if (start.get('q')) q.value = start.get('q')
    const si = start.get('industry')
    if (si && chips.some((c) => c.dataset.industry === si)) {
      industry = si
      chips.forEach((x) => x.setAttribute('aria-pressed', String(x.dataset.industry === si)))
    }
    apply()
    // The bar gets its glass background once it sticks under the header.
    const bar = $('.shop-bar')
    if (bar) {
      const stickAt = () => (hdr ? hdr.offsetHeight : 0)
      const onS = () => bar.classList.toggle('is-stuck', bar.getBoundingClientRect().top <= stickAt() + 1)
      addEventListener('scroll', onS, { passive: true }); onS()
    }
  }

  /* ---------- Footer: back to top ---------- */
  $$('[data-to-top]').forEach((b) => b.addEventListener('click', () => scrollTo({ top: 0, behavior: reduceMotion ? 'auto' : 'smooth' })))

  /* ---------- Product hero stage: flattens as you scroll ---------- */
  const stage = $('.stage')
  if (stage && !reduceMotion) {
    let raf = 0
    const upd = () => {
      raf = 0
      const r = stage.getBoundingClientRect()
      const p = clamp((innerHeight - r.top) / (innerHeight * 0.9), 0, 1)
      stage.style.setProperty('--rx', `${(22 - 22 * p).toFixed(2)}deg`)
      stage.style.setProperty('--s', (0.94 + 0.06 * p).toFixed(3))
    }
    const kick = () => { if (!raf) raf = requestAnimationFrame(upd) }
    addEventListener('scroll', kick, { passive: true })
    addEventListener('resize', kick)
    upd()
  }

  /* ---------- Pointer tilt for .tiltable scenes ---------- */
  if (finePointer && !reduceMotion) {
    $$('.tiltable').forEach((scene) => {
      const win = $('.window', scene)
      let raf = 0, tx = 0, ty = 0
      scene.addEventListener('pointermove', (e) => {
        const r = scene.getBoundingClientRect()
        tx = (e.clientX - r.left) / r.width - 0.5
        ty = (e.clientY - r.top) / r.height - 0.5
        if (!raf) raf = requestAnimationFrame(() => { raf = 0; win.style.transform = `rotateX(${(-ty * 5).toFixed(2)}deg) rotateY(${(tx * 7).toFixed(2)}deg)` })
      })
      scene.addEventListener('pointerleave', () => { win.style.transform = '' })
    })
  }

  /* ---------- Screen viewer tabs ---------- */
  $$('[data-viewer]').forEach((viewer) => {
    const tabs = $$('[role="tab"]', viewer)
    const light = $('.vimg-light', viewer)
    const dark = $('.vimg-dark', viewer)
    const cap = $('.viewer__cap', viewer)
    // data-viewer is relative to the site root; data-root on <html> (written by the build) says how deep
    // this page is, so the path stays right wherever the page lives (products/chittill/ → ../../).
    const base = (doc.dataset.root || '') + viewer.dataset.viewer
    const preload = (s) => new Promise((res) => { const im = new Image(); im.onload = im.onerror = res; im.src = s })
    // Warm the cache once the viewer is close, so switching tabs is instant.
    new IntersectionObserver((en, o) => {
      if (!en[0].isIntersecting) return
      o.disconnect()
      tabs.forEach((t) => { preload(`${base}${t.dataset.shot}.webp`); if (t.dataset.dark) preload(`${base}${t.dataset.dark}.webp`) })
    }, { rootMargin: '600px' }).observe(viewer)
    tabs.forEach((tab, idx) => {
      tab.addEventListener('click', async () => {
        if (tab.getAttribute('aria-selected') === 'true') return
        tabs.forEach((t) => { t.setAttribute('aria-selected', String(t === tab)); t.tabIndex = t === tab ? 0 : -1 })
        const ls = `${base}${tab.dataset.shot}.webp`
        const ds = `${base}${tab.dataset.dark || tab.dataset.shot}.webp`
        light.classList.add('is-swapping'); dark.classList.add('is-swapping')
        await Promise.all([preload(ls), preload(ds), new Promise((r) => setTimeout(r, 180))])
        light.src = ls; dark.src = ds
        light.alt = dark.alt = `${tab.textContent.trim()} screen`
        cap.textContent = tab.dataset.cap
        requestAnimationFrame(() => { light.classList.remove('is-swapping'); dark.classList.remove('is-swapping') })
      })
      tab.addEventListener('keydown', (e) => {
        if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return
        const n = tabs[(idx + (e.key === 'ArrowRight' ? 1 : tabs.length - 1)) % tabs.length]
        n.focus(); n.click()
      })
    })
  })

  /* ---------- Sticky sub-nav: highlight the section in view ---------- */
  const sublinks = $$('.subnav__links a')
  if (sublinks.length) {
    const map = new Map(sublinks.map((a) => [a.getAttribute('href').slice(1), a]))
    const sio = new IntersectionObserver((entries) => {
      entries.forEach((e) => {
        if (!e.isIntersecting) return
        sublinks.forEach((a) => a.classList.remove('is-active'))
        map.get(e.target.id)?.classList.add('is-active')
      })
    }, { rootMargin: '-45% 0px -50% 0px' })
    map.forEach((_, id) => { const s = document.getElementById(id); if (s) sio.observe(s) })
  }

  /* ---------- Small notice at the bottom of the screen ---------- */
  const root = doc.dataset.root || ''
  let toast, toastTimer
  const showToast = (iconId, text, linkText, href) => {
    if (!toast) {
      toast = document.createElement('div')
      toast.className = 'toast'
      toast.setAttribute('role', 'status')
      document.body.append(toast)
    }
    toast.innerHTML = `<svg class="i" aria-hidden="true"><use href="#i-${iconId}"/></svg><span>${text}</span>${linkText ? `<a href="${href}">${linkText}</a>` : ''}`
    requestAnimationFrame(() => toast.classList.add('is-on'))
    clearTimeout(toastTimer)
    toastTimer = setTimeout(() => toast.classList.remove('is-on'), 5000)
  }

  /* ---------- Placeholders until the real links are set in site-data.js ---------- */
  // Download buttons with url '#'
  $$('[data-download-pending]').forEach((a) => a.addEventListener('click', (e) => {
    e.preventDefault()
    showToast('download', 'The download is coming soon. Meanwhile, we’ll set it up for you in a free demo.', 'Book a demo', toFile(root + 'contact/?interest=demo'))
  }))
  // WhatsApp button without a number yet
  $$('[data-wa-pending]').forEach((a) => a.addEventListener('click', (e) => {
    e.preventDefault()
    showToast('message', 'Our WhatsApp line is coming soon. Send us a message here and we’ll reply within a working day.', 'Contact us', toFile(root + 'contact/'))
  }))

  /* ---------- Floating WhatsApp button ---------- */
  const fab = $('.wa-fab')
  if (fab) {
    // The chat opens with a friendly first line that mentions the page they were reading.
    const num = fab.dataset.wa
    if (num) {
      const product = document.title.split('·')[0].trim()
      const msg = document.body.dataset.page.startsWith('product-')
        ? `Hi CraftedSoft! I'd like to know more about ${product}.`
        : 'Hi CraftedSoft! I have a question about your software.'
      fab.href = `https://wa.me/${num}?text=${encodeURIComponent(msg)}`
    }
    // Peek the "Questions? Chat with us" bubble once per visit, a few seconds in.
    let peeked = false
    try { peeked = sessionStorage.getItem('cs-wa-peek') === '1' } catch (e) { /* storage blocked */ }
    if (!peeked && !reduceMotion && finePointer) {
      setTimeout(() => {
        fab.classList.add('is-peek')
        try { sessionStorage.setItem('cs-wa-peek', '1') } catch (e) { /* ignore */ }
        setTimeout(() => fab.classList.remove('is-peek'), 4500)
      }, 5000)
    }
  }

  /* ---------- Analytics events (only if an analytics service is set in site-data.js) ---------- */
  const track = (name) => {
    try {
      if (typeof window.plausible === 'function') window.plausible(name, { props: { page: location.pathname } })
      if (typeof window.gtag === 'function') window.gtag('event', name.toLowerCase().replace(/\s+/g, '_'), { page_path: location.pathname })
    } catch (e) { /* never let analytics break the page */ }
  }
  document.addEventListener('click', (e) => {
    const a = e.target.closest && e.target.closest('a, button')
    if (!a) return
    if (a.dataset.track) return track(a.dataset.track)
    if (a.matches('.btn-dl, .btn--dl')) return track('Download')
    const href = a.getAttribute('href') || ''
    if (/contact\/(index\.html)?\?interest=demo/.test(href) || /book a (free )?demo/i.test(a.textContent)) return track('Book demo')
    if (/contact\/(index\.html)?\?interest=custom/.test(href)) return track('Custom project')
  })
  $('#contact-form')?.addEventListener('submit', () => track('Contact form'))

  /* ---------- Legal pages: highlight the section being read ---------- */
  const tocLinks = $$('.legal-toc a')
  if (tocLinks.length) {
    const byId = new Map(tocLinks.map((a) => [a.getAttribute('href').slice(1), a]))
    const lio = new IntersectionObserver((entries) => {
      entries.forEach((en) => {
        if (!en.isIntersecting) return
        tocLinks.forEach((a) => a.classList.remove('is-active'))
        byId.get(en.target.id)?.classList.add('is-active')
      })
    }, { rootMargin: '-30% 0px -60% 0px' })
    byId.forEach((_, id) => { const s = document.getElementById(id); if (s) lio.observe(s) })
  }

  /* ---------- Manifesto: words light up as you scroll ---------- */
  $$('[data-manifesto]').forEach((el) => {
    if (reduceMotion) return
    const words = []
    const split = (node) => {
      ;[...node.childNodes].forEach((n) => {
        if (n.nodeType === 3) {
          const frag = document.createDocumentFragment()
          n.textContent.split(/(\s+)/).forEach((part) => {
            if (!part) return
            if (/^\s+$/.test(part)) { frag.append(part); return }
            const w = document.createElement('span')
            w.className = 'w'
            w.textContent = part
            words.push(w)
            frag.append(w)
          })
          n.replaceWith(frag)
        } else if (n.nodeType === 1) split(n)
      })
    }
    split(el)
    let raf = 0, lit = -1
    const update = () => {
      raf = 0
      const r = el.getBoundingClientRect()
      // Starts lighting when the text enters the lower part of the screen, done by the time it reaches the upper third.
      const p = clamp((innerHeight * 0.85 - r.top) / (r.height + innerHeight * 0.35), 0, 1)
      const n = Math.round(p * words.length)
      if (n === lit) return
      lit = n
      words.forEach((w, i) => w.classList.toggle('on', i < n))
    }
    addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(update) }, { passive: true })
    addEventListener('resize', update)
    update()
  })

  /* ---------- Capability explorer (What we build) ---------- */
  $$('[data-explorer]').forEach((xp) => {
    const tabs = $$('[role="tab"]', xp)
    const select = (tab, focus) => {
      tabs.forEach((t) => {
        const on = t === tab
        t.setAttribute('aria-selected', String(on))
        t.tabIndex = on ? 0 : -1
        document.getElementById(t.getAttribute('aria-controls'))?.classList.toggle('is-active', on)
      })
      if (focus) tab.focus()
      // Keep the chosen pill visible when the tabs are a scrolling row (phones).
      tab.scrollIntoView({ block: 'nearest', inline: 'nearest', behavior: reduceMotion ? 'auto' : 'smooth' })
    }
    tabs.forEach((tab, i) => {
      tab.addEventListener('click', () => select(tab, false))
      tab.addEventListener('keydown', (e) => {
        const step = { ArrowDown: 1, ArrowRight: 1, ArrowUp: -1, ArrowLeft: -1 }[e.key]
        if (e.key === 'Home') { e.preventDefault(); select(tabs[0], true) }
        else if (e.key === 'End') { e.preventDefault(); select(tabs[tabs.length - 1], true) }
        else if (step) { e.preventDefault(); select(tabs[(i + step + tabs.length) % tabs.length], true) }
      })
    })
  })

  /* ---------- Contact form ---------- */
  const form = $('#contact-form')
  if (form) {
    const qs = new URLSearchParams(location.search)
    const interests = $$('input[name="interest"]', form)
    const productGroup = $('#product-group')
    // The product question only matters when it isn't a brand-new custom build.
    const syncProduct = () => {
      const v = form.elements.interest.value
      if (productGroup) productGroup.hidden = v === 'Custom software'
    }
    interests.forEach((r) => r.addEventListener('change', syncProduct))
    const want = qs.get('interest')
    if (want) {
      const map = { custom: 'Custom software', demo: 'Product demo', pricing: 'Pricing', support: 'Support' }
      const target = map[want.toLowerCase()] || want
      const r = interests.find((x) => x.value.toLowerCase() === target.toLowerCase())
      if (r) r.checked = true
    }
    syncProduct()
    // ?product=ChitTill or ?product=ChitTill%20Pro → pick the ChitTill pill and keep the plan in the message.
    const product = qs.get('product')
    if (product) {
      const pills = $$('input[name="product"]', form).filter((x) => x.value)
      const r = pills.find((x) => x.value === product) || pills.find((x) => product.toLowerCase().startsWith(x.value.toLowerCase()))
      if (r) {
        r.checked = true
        if (r.value !== product) {
          const h = document.createElement('input')
          h.type = 'hidden'; h.name = 'productDetail'; h.value = product
          form.append(h)
        }
      }
    }
    const note = $('#form-note')
    form.addEventListener('submit', (e) => {
      e.preventDefault()
      const d = Object.fromEntries(new FormData(form))
      let ok = true
      ;['name', 'phone'].forEach((k) => {
        const el = form.elements[k]
        const bad = !String(d[k] || '').trim() || (k === 'phone' && String(d[k]).replace(/\D/g, '').length < 10)
        el.setAttribute('aria-invalid', bad ? 'true' : 'false')
        if (bad) ok = false
      })
      if (!ok) { note.textContent = 'Please add your name and a 10-digit mobile number.'; note.className = 'form__note is-err'; return }
      const text = [
        `Hi CraftedSoft, I'm interested in: ${d.interest}${d.product && d.interest !== 'Custom software' ? ` (${d.productDetail || d.product})` : ''}.`,
        `Name: ${d.name}`,
        d.business && `Business: ${d.business}`,
        `Mobile: ${d.phone}`,
        d.city && `City: ${d.city}`,
        d.message && `\n${d.message}`
      ].filter(Boolean).join('\n')
      if (C.whatsapp) window.open(`https://wa.me/${C.whatsapp}?text=${encodeURIComponent(text)}`, '_blank', 'noopener')
      else location.href = `mailto:${C.email}?subject=${encodeURIComponent(`${d.interest}: ${d.business || d.name}`)}&body=${encodeURIComponent(text)}`
      note.textContent = 'Thank you! Your message is ready to send. We reply within one working day.'
      note.className = 'form__note is-ok'
    })
  }
})()


/* ---------- Accent colour picker ----------
   Swatches come from accents in site-data.js (built into every page). The choice is stored in localStorage
   'cs-accent' and re-applied before first paint by the small script in each page's <head>. */
;(function () {
  const d = document.documentElement
  const swatches = document.querySelectorAll('[data-accent]')
  if (!swatches.length) return
  const def = swatches[0].dataset.accent.toLowerCase()
  const mark = (c) => swatches.forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.accent.toLowerCase() === c)))
  let current = def
  try {
    const saved = localStorage.getItem('cs-accent')
    if (saved && /^#[0-9a-f]{6}$/i.test(saved)) current = saved.toLowerCase()
  } catch (e) { /* storage blocked */ }
  mark(current)
  // Header button opens the colour card; it stays open while trying colours, closes on outside click / Esc.
  const btn = document.querySelector('.accbtn')
  const pop = document.getElementById('accpop')
  const show = (v) => { if (!btn) return; pop.hidden = !v; btn.setAttribute('aria-expanded', String(v)) }
  if (btn) {
    btn.addEventListener('click', (e) => { e.stopPropagation(); show(pop.hidden) })
    document.addEventListener('click', (e) => { if (!pop.hidden && !e.target.closest('.accdd')) show(false) })
    document.addEventListener('keydown', (e) => { if (e.key === 'Escape' && !pop.hidden) { show(false); btn.focus() } })
  }
  document.addEventListener('click', (e) => {
    const b = e.target.closest && e.target.closest('[data-accent], [data-accent-reset]')
    if (!b) return
    const c = (b.dataset.accent || def).toLowerCase()
    if (c === def) d.style.removeProperty('--brand')
    else d.style.setProperty('--brand', c)
    try { c === def ? localStorage.removeItem('cs-accent') : localStorage.setItem('cs-accent', c) } catch (err) { /* storage blocked */ }
    mark(c)
  })
})()
