/* CraftedSoft: site behaviour (no dependencies).
   All markup is static HTML (generated by tools/build.mjs); this file only adds
   interaction: theme, menus, reveal-on-scroll, 3D effects, tabs and the form. */
;(function () {
  const SITE = window.CS_SITE || { contact: {}, products: [] }
  const C = SITE.contact || {}
  const doc = document.documentElement
  const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches
  const finePointer = matchMedia('(pointer: fine)').matches
  const $ = (s, r = document) => r.querySelector(s)
  const $$ = (s, r = document) => [...r.querySelectorAll(s)]
  const clamp = (v, a, b) => Math.min(b, Math.max(a, v))

  /* ---------- Reveal on scroll ----------
     Anything already on screen at load is shown at once (no fade), so a page
     never "re-animates" when you navigate to it. Only content further down fades in. */
  const reveals = $$('.reveal')
  const vh = innerHeight
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e) => { if (e.isIntersecting) { e.target.classList.add('is-in'); io.unobserve(e.target) } })
  }, { rootMargin: '0px 0px -6% 0px', threshold: 0.06 })
  reveals.forEach((el) => {
    if (el.getBoundingClientRect().top < vh) {
      el.classList.add('no-anim', 'is-in')
      return
    }
    const sibs = $$(':scope > .reveal', el.parentElement)
    const i = sibs.indexOf(el)
    if (i > 0) el.style.setProperty('--d', `${Math.min(i, 5) * 0.06}s`)
    io.observe(el)
  })
  requestAnimationFrame(() => requestAnimationFrame(() => $$('.no-anim').forEach((el) => el.classList.remove('no-anim'))))

  /* ---------- Theme ---------- */
  const setTheme = (t, save) => {
    doc.dataset.theme = t
    const meta = $('meta[name="theme-color"]')
    if (meta) meta.content = t === 'dark' ? '#0a0b0f' : '#ffffff'
    if (save) try { localStorage.setItem('cs-theme', t) } catch (e) { /* storage blocked */ }
    $$('.theme-btn').forEach((b) => {
      const label = t === 'dark' ? 'Switch to day mode' : 'Switch to night mode'
      b.setAttribute('aria-label', label)
      b.title = label
    })
  }
  setTheme(doc.dataset.theme || 'light', false)
  $$('.theme-btn').forEach((b) =>
    b.addEventListener('click', () => {
      const next = doc.dataset.theme === 'dark' ? 'light' : 'dark'
      // Cross-fade the whole page between themes where supported.
      if (document.startViewTransition && !reduceMotion) document.startViewTransition(() => setTheme(next, true))
      else setTheme(next, true)
    })
  )
  matchMedia('(prefers-color-scheme: dark)').addEventListener('change', (e) => {
    let saved = null
    try { saved = localStorage.getItem('cs-theme') } catch (err) { /* ignore */ }
    if (!saved) setTheme(e.matches ? 'dark' : 'light', false)
  })

  /* ---------- Header ---------- */
  const hdr = $('#hdr')
  if (hdr) {
    const onScroll = () => hdr.classList.toggle('is-scrolled', scrollY > 8)
    onScroll()
    addEventListener('scroll', onScroll, { passive: true })

    const dd = $('#dd-products')
    if (dd) {
      const btn = $('button', dd)
      let timer
      const open = (v) => { dd.classList.toggle('is-open', v); hdr.classList.toggle('dd-open', v); btn.setAttribute('aria-expanded', String(v)) }
      btn.addEventListener('click', () => open(!dd.classList.contains('is-open')))
      if (finePointer) {
        dd.addEventListener('mouseenter', () => { clearTimeout(timer); open(true) })
        dd.addEventListener('mouseleave', () => { timer = setTimeout(() => open(false), 160) })
      }
      document.addEventListener('click', (e) => { if (!dd.contains(e.target)) open(false) })
      document.addEventListener('keydown', (e) => { if (e.key === 'Escape') open(false) })
    }

    // Sliding highlight that follows the pointer across the main links.
    const nav = $('.hdr__nav', hdr)
    const ink = $('.hdr__ink', hdr)
    if (nav && ink && finePointer) {
      const targets = $$(':scope > a, :scope > .dd > button', nav)
      const moveTo = (el) => {
        const nr = nav.getBoundingClientRect()
        const r = el.getBoundingClientRect()
        ink.style.width = `${r.width}px`
        ink.style.transform = `translateX(${r.left - nr.left}px)`
        ink.style.opacity = '1'
      }
      targets.forEach((el) => el.addEventListener('mouseenter', () => moveTo(el)))
      nav.addEventListener('mouseleave', () => { ink.style.opacity = '0' })
    }

    // Mobile: full-screen menu sheet.
    const burger = $('.burger', hdr)
    const mnav = $('#mnav')
    if (burger && mnav) {
      const setMenu = (v) => {
        burger.setAttribute('aria-expanded', String(v))
        burger.setAttribute('aria-label', v ? 'Close menu' : 'Open menu')
        hdr.classList.toggle('is-open', v)
        doc.style.overflow = v ? 'hidden' : ''
      }
      burger.addEventListener('click', () => setMenu(!hdr.classList.contains('is-open')))
      $$('a', mnav).forEach((a) => a.addEventListener('click', () => setMenu(false)))
      document.addEventListener('keydown', (e) => { if (e.key === 'Escape') setMenu(false) })
      addEventListener('resize', () => { if (innerWidth > 860) setMenu(false) })
    }
  }

  /* ---------- Product pages: hand the top of the screen to the product bar ---------- */
  const subnav = $('.subnav')
  if (hdr && subnav) {
    const sentinel = document.createElement('div')
    sentinel.setAttribute('aria-hidden', 'true')
    subnav.before(sentinel)
    // One bar at a time: the moment the product bar reaches the header, the header steps away, in
    // either scroll direction, and only returns once you are back above the product bar's place.
    let raf = 0
    const update = () => {
      raf = 0
      document.body.classList.toggle('nav-up', sentinel.getBoundingClientRect().top <= hdr.offsetHeight)
    }
    addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(update) }, { passive: true })
    addEventListener('resize', update)
    update()
  }

  /* ---------- Product filters ---------- */
  const filters = $('#filters')
  if (filters) {
    filters.addEventListener('click', (e) => {
      const b = e.target.closest('button')
      if (!b) return
      $$('button', filters).forEach((x) => x.setAttribute('aria-pressed', String(x === b)))
      const f = b.dataset.f
      $$('.pgrid .pcard').forEach((c) => { c.style.display = f === 'All' || c.dataset.cat === f || c.dataset.cat === '*' ? '' : 'none' })
    })
  }

  /* ---------- Product hero stage: flattens as you scroll ---------- */
  const stage = $('.stage')
  if (stage && !reduceMotion) {
    let raf = 0
    const upd = () => {
      raf = 0
      const r = stage.getBoundingClientRect()
      const p = clamp((innerHeight - r.top) / (innerHeight * 0.9), 0, 1)
      stage.style.setProperty('--rx', `${(22 - 22 * p).toFixed(2)}deg`)
      stage.style.setProperty('--s', (0.94 + 0.06 * p).toFixed(3))
    }
    const kick = () => { if (!raf) raf = requestAnimationFrame(upd) }
    addEventListener('scroll', kick, { passive: true })
    addEventListener('resize', kick)
    upd()
  }

  /* ---------- Pointer tilt for .tiltable scenes ---------- */
  if (finePointer && !reduceMotion) {
    $$('.tiltable').forEach((scene) => {
      const win = $('.window', scene)
      let raf = 0, tx = 0, ty = 0
      scene.addEventListener('pointermove', (e) => {
        const r = scene.getBoundingClientRect()
        tx = (e.clientX - r.left) / r.width - 0.5
        ty = (e.clientY - r.top) / r.height - 0.5
        if (!raf) raf = requestAnimationFrame(() => { raf = 0; win.style.transform = `rotateX(${(-ty * 5).toFixed(2)}deg) rotateY(${(tx * 7).toFixed(2)}deg)` })
      })
      scene.addEventListener('pointerleave', () => { win.style.transform = '' })
    })
  }

  /* ---------- Screen viewer tabs ---------- */
  $$('[data-viewer]').forEach((viewer) => {
    const tabs = $$('[role="tab"]', viewer)
    const light = $('.vimg-light', viewer)
    const dark = $('.vimg-dark', viewer)
    const cap = $('.viewer__cap', viewer)
    const base = viewer.dataset.viewer
    const preload = (s) => new Promise((res) => { const im = new Image(); im.onload = im.onerror = res; im.src = s })
    // Warm the cache once the viewer is close, so switching tabs is instant.
    new IntersectionObserver((en, o) => {
      if (!en[0].isIntersecting) return
      o.disconnect()
      tabs.forEach((t) => { preload(`${base}${t.dataset.shot}.webp`); if (t.dataset.dark) preload(`${base}${t.dataset.dark}.webp`) })
    }, { rootMargin: '600px' }).observe(viewer)
    tabs.forEach((tab, idx) => {
      tab.addEventListener('click', async () => {
        if (tab.getAttribute('aria-selected') === 'true') return
        tabs.forEach((t) => { t.setAttribute('aria-selected', String(t === tab)); t.tabIndex = t === tab ? 0 : -1 })
        const ls = `${base}${tab.dataset.shot}.webp`
        const ds = `${base}${tab.dataset.dark || tab.dataset.shot}.webp`
        light.classList.add('is-swapping'); dark.classList.add('is-swapping')
        await Promise.all([preload(ls), preload(ds), new Promise((r) => setTimeout(r, 180))])
        light.src = ls; dark.src = ds
        light.alt = dark.alt = `${tab.textContent.trim()} screen`
        cap.textContent = tab.dataset.cap
        requestAnimationFrame(() => { light.classList.remove('is-swapping'); dark.classList.remove('is-swapping') })
      })
      tab.addEventListener('keydown', (e) => {
        if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return
        const n = tabs[(idx + (e.key === 'ArrowRight' ? 1 : tabs.length - 1)) % tabs.length]
        n.focus(); n.click()
      })
    })
  })

  /* ---------- Sticky sub-nav: highlight the section in view ---------- */
  const sublinks = $$('.subnav__links a')
  if (sublinks.length) {
    const map = new Map(sublinks.map((a) => [a.getAttribute('href').slice(1), a]))
    const sio = new IntersectionObserver((entries) => {
      entries.forEach((e) => {
        if (!e.isIntersecting) return
        sublinks.forEach((a) => a.classList.remove('is-active'))
        map.get(e.target.id)?.classList.add('is-active')
      })
    }, { rootMargin: '-45% 0px -50% 0px' })
    map.forEach((_, id) => { const s = document.getElementById(id); if (s) sio.observe(s) })
  }

  /* ---------- Download buttons whose link isn't set yet (url: '#' in site-data.js) ---------- */
  const pending = $$('[data-download-pending]')
  if (pending.length) {
    const root = doc.dataset.root || ''
    let toast, timer
    const show = () => {
      if (!toast) {
        toast = document.createElement('div')
        toast.className = 'toast'
        toast.setAttribute('role', 'status')
        toast.innerHTML = `<svg class="i" aria-hidden="true"><use href="#i-download"/></svg><span>The download is coming soon. Meanwhile, we'll set it up for you in a free demo.</span><a href="${root}contact.html?interest=demo">Book a demo</a>`
        document.body.append(toast)
      }
      requestAnimationFrame(() => toast.classList.add('is-on'))
      clearTimeout(timer)
      timer = setTimeout(() => toast.classList.remove('is-on'), 5000)
    }
    pending.forEach((a) => a.addEventListener('click', (e) => { e.preventDefault(); show() }))
  }

  /* ---------- Manifesto: words light up as you scroll ---------- */
  $$('[data-manifesto]').forEach((el) => {
    if (reduceMotion) return
    const words = []
    const split = (node) => {
      ;[...node.childNodes].forEach((n) => {
        if (n.nodeType === 3) {
          const frag = document.createDocumentFragment()
          n.textContent.split(/(\s+)/).forEach((part) => {
            if (!part) return
            if (/^\s+$/.test(part)) { frag.append(part); return }
            const w = document.createElement('span')
            w.className = 'w'
            w.textContent = part
            words.push(w)
            frag.append(w)
          })
          n.replaceWith(frag)
        } else if (n.nodeType === 1) split(n)
      })
    }
    split(el)
    let raf = 0, lit = -1
    const update = () => {
      raf = 0
      const r = el.getBoundingClientRect()
      // Starts lighting when the text enters the lower part of the screen, done by the time it reaches the upper third.
      const p = clamp((innerHeight * 0.85 - r.top) / (r.height + innerHeight * 0.35), 0, 1)
      const n = Math.round(p * words.length)
      if (n === lit) return
      lit = n
      words.forEach((w, i) => w.classList.toggle('on', i < n))
    }
    addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(update) }, { passive: true })
    addEventListener('resize', update)
    update()
  })

  /* ---------- Capability explorer (What we build) ---------- */
  $$('[data-explorer]').forEach((xp) => {
    const tabs = $$('[role="tab"]', xp)
    const select = (tab, focus) => {
      tabs.forEach((t) => {
        const on = t === tab
        t.setAttribute('aria-selected', String(on))
        t.tabIndex = on ? 0 : -1
        document.getElementById(t.getAttribute('aria-controls'))?.classList.toggle('is-active', on)
      })
      if (focus) tab.focus()
      // Keep the chosen pill visible when the tabs are a scrolling row (phones).
      tab.scrollIntoView({ block: 'nearest', inline: 'nearest', behavior: reduceMotion ? 'auto' : 'smooth' })
    }
    tabs.forEach((tab, i) => {
      tab.addEventListener('click', () => select(tab, false))
      tab.addEventListener('keydown', (e) => {
        const step = { ArrowDown: 1, ArrowRight: 1, ArrowUp: -1, ArrowLeft: -1 }[e.key]
        if (e.key === 'Home') { e.preventDefault(); select(tabs[0], true) }
        else if (e.key === 'End') { e.preventDefault(); select(tabs[tabs.length - 1], true) }
        else if (step) { e.preventDefault(); select(tabs[(i + step + tabs.length) % tabs.length], true) }
      })
    })
  })

  /* ---------- Contact form ---------- */
  const form = $('#contact-form')
  if (form) {
    const qs = new URLSearchParams(location.search)
    const interests = $$('input[name="interest"]', form)
    const productGroup = $('#product-group')
    // The product question only matters when it isn't a brand-new custom build.
    const syncProduct = () => {
      const v = form.elements.interest.value
      if (productGroup) productGroup.hidden = v === 'Custom software'
    }
    interests.forEach((r) => r.addEventListener('change', syncProduct))
    const want = qs.get('interest')
    if (want) {
      const map = { custom: 'Custom software', demo: 'Product demo', pricing: 'Pricing', support: 'Support' }
      const target = map[want.toLowerCase()] || want
      const r = interests.find((x) => x.value.toLowerCase() === target.toLowerCase())
      if (r) r.checked = true
    }
    syncProduct()
    // ?product=ChitTill or ?product=ChitTill%20Pro → pick the ChitTill pill and keep the plan in the message.
    const product = qs.get('product')
    if (product) {
      const pills = $$('input[name="product"]', form).filter((x) => x.value)
      const r = pills.find((x) => x.value === product) || pills.find((x) => product.toLowerCase().startsWith(x.value.toLowerCase()))
      if (r) {
        r.checked = true
        if (r.value !== product) {
          const h = document.createElement('input')
          h.type = 'hidden'; h.name = 'productDetail'; h.value = product
          form.append(h)
        }
      }
    }
    const note = $('#form-note')
    form.addEventListener('submit', (e) => {
      e.preventDefault()
      const d = Object.fromEntries(new FormData(form))
      let ok = true
      ;['name', 'phone'].forEach((k) => {
        const el = form.elements[k]
        const bad = !String(d[k] || '').trim() || (k === 'phone' && String(d[k]).replace(/\D/g, '').length < 10)
        el.setAttribute('aria-invalid', bad ? 'true' : 'false')
        if (bad) ok = false
      })
      if (!ok) { note.textContent = 'Please add your name and a 10-digit mobile number.'; note.className = 'form__note is-err'; return }
      const text = [
        `Hi CraftedSoft, I'm interested in: ${d.interest}${d.product && d.interest !== 'Custom software' ? ` (${d.productDetail || d.product})` : ''}.`,
        `Name: ${d.name}`,
        d.business && `Business: ${d.business}`,
        `Mobile: ${d.phone}`,
        d.city && `City: ${d.city}`,
        d.message && `\n${d.message}`
      ].filter(Boolean).join('\n')
      if (C.whatsapp) window.open(`https://wa.me/${C.whatsapp}?text=${encodeURIComponent(text)}`, '_blank', 'noopener')
      else location.href = `mailto:${C.email}?subject=${encodeURIComponent(`${d.interest}: ${d.business || d.name}`)}&body=${encodeURIComponent(text)}`
      note.textContent = 'Thank you! Your message is ready to send. We reply within one working day.'
      note.className = 'form__note is-ok'
    })
  }
})()
